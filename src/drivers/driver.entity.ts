import {
  Check,
  Column,
  CreateDateColumn,
  Entity,
  JoinColumn,
  ManyToOne,
  OneToOne,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from "typeorm";
import { User } from "../users/user.entity.js";

/**
 * Where a driver is with the fleet (D56).
 * - `onboarding`: approved, but contract, deposit or vehicle is still missing. New drivers start here.
 * - `active`: all three onboarding steps done. Only active drivers are billed and reminded (M2, M6).
 * - `inactive`: left the fleet. Cannot log in; can be reactivated.
 */
export enum DriverStatus {
  onboarding = "onboarding",
  active = "active",
  inactive = "inactive",
}

/**
 * How a driver left the fleet (D81): the client's three answers, always noted when a driver is deactivated or sent
 * to collections.
 */
export enum DriverLeftReason {
  contractEnded = "contract_ended",
  badDriver = "bad_driver",
  cooperativeReturnedCar = "cooperative_returned_car",
}

/** Largest amount a 4-byte `integer` column holds: the only limit on the deposit amount (D82). */
export const MAX_DEPOSIT_CENTS = 2_147_483_647;

/**
 * A driver renting a car from the fleet. Maps to the `drivers` table.
 *
 * Created when an admin approves an application (D26), in `onboarding` (D56). Payments are matched to
 * drivers of any status (a deposit arrives before the driver is active), which is why email and phone
 * must each belong to only one driver.
 */
@Entity("drivers")
@Check("drivers_email_lowercase", `"email" = lower("email")`)
@Check("drivers_phone_e164_us", `"phone" ~ '^\\+1[0-9]{10}$'`)
// Active only with all three onboarding steps done (D56). Enforced here, not only in code, so no code path, script
// or manual SQL can make a driver active without them.
@Check(
  "drivers_active_is_onboarded",
  `"status" <> 'active' OR ("contract_signed_at" IS NOT NULL AND "deposit_paid_at" IS NOT NULL AND "vehicle_assigned_at" IS NOT NULL)`,
)
// Leaving (D81): a reason and its date come together, and only an inactive driver has left.
@Check(
  "drivers_left_shape",
  `("left_reason" IS NULL) = ("left_at" IS NULL) AND ("left_reason" IS NULL OR "status" = 'inactive')`,
)
// In collections only when inactive and with the reason noted: "we always have to note how they left" (D81).
@Check(
  "drivers_collections_shape",
  `"sent_to_collections_at" IS NULL OR ("status" = 'inactive' AND "left_reason" IS NOT NULL)`,
)
// A deposit amount exists only while the deposit step is ticked, and is a positive whole number of cents (D82).
@Check(
  "drivers_deposit_amount_shape",
  `"deposit_paid_cents" IS NULL OR ("deposit_paid_at" IS NOT NULL AND "deposit_paid_cents" > 0)`,
)
export class Driver {
  /** Generated by the database (gen_random_uuid()). */
  @PrimaryGeneratedColumn("uuid")
  id: string;

  @Column({ name: "first_name", type: "varchar", length: 100 })
  firstName: string;

  @Column({ name: "last_name", type: "varchar", length: 100 })
  lastName: string;

  /** Stored lower-case (enforced by the CHECK above). Unique across drivers. */
  @Column({ type: "varchar", length: 254, unique: true })
  email: string;

  /**
   * US number in E.164 format, e.g. `+13125550123`: `+1` followed by 10 digits.
   * One stored format means a lookup by phone can never miss because of formatting
   * (`(312) 555-0123` vs `3125550123`). The CHECK above makes the database reject
   * anything else; the code converts the application's 10 digits before saving.
   */
  @Column({ type: "varchar", length: 12, unique: true })
  phone: string;

  /** New drivers start `onboarding`; they become `active` when the last onboarding step is ticked (D56). */
  @Column({
    type: "enum",
    enum: DriverStatus,
    enumName: "driver_status",
    default: DriverStatus.onboarding,
  })
  status: DriverStatus;

  // The three onboarding steps, in any order (D56): when each was ticked, and by which admin. A null admin with a
  // date means "done before this system" (set by the migration for drivers imported as active).

  @Column({ name: "contract_signed_at", type: "timestamptz", nullable: true })
  contractSignedAt: Date | null;

  @Column({ name: "contract_signed_by_id", type: "uuid", nullable: true })
  contractSignedById: string | null;

  /** Foreign key to `users`; `SET NULL` so removing an admin account never blocks or removes a driver. */
  @ManyToOne(() => User, { nullable: true, onDelete: "SET NULL" })
  @JoinColumn({ name: "contract_signed_by_id" })
  contractSignedBy?: User | null;

  @Column({ name: "deposit_paid_at", type: "timestamptz", nullable: true })
  depositPaidAt: Date | null;

  @Column({ name: "deposit_paid_by_id", type: "uuid", nullable: true })
  depositPaidById: string | null;

  @ManyToOne(() => User, { nullable: true, onDelete: "SET NULL" })
  @JoinColumn({ name: "deposit_paid_by_id" })
  depositPaidBy?: User | null;

  /**
   * How much the deposit was, in cents, typed when the step was ticked (D82). Null until recorded; drivers whose step
   * was ticked before this existed have no amount. Cleared when the step is un-ticked.
   */
  @Column({ name: "deposit_paid_cents", type: "integer", nullable: true })
  depositPaidCents: number | null;

  @Column({ name: "vehicle_assigned_at", type: "timestamptz", nullable: true })
  vehicleAssignedAt: Date | null;

  @Column({ name: "vehicle_assigned_by_id", type: "uuid", nullable: true })
  vehicleAssignedById: string | null;

  @ManyToOne(() => User, { nullable: true, onDelete: "SET NULL" })
  @JoinColumn({ name: "vehicle_assigned_by_id" })
  vehicleAssignedBy?: User | null;

  /**
   * When an admin archived the driver (D80); null = not archived. A flag, not a status: an archived driver keeps
   * `active` or `inactive`, so unarchiving restores it exactly. Archived drivers are hidden from the normal list and
   * are not billed or reminded (spec sections 7 and 8); payments from them are still matched.
   */
  @Column({ name: "archived_at", type: "timestamptz", nullable: true })
  archivedAt: Date | null;

  /**
   * How the driver left, when it was noted and by whom (D81). Set when they are deactivated or sent to collections;
   * cleared on reactivation. Null for drivers deactivated before this existed ("reason not recorded").
   */
  @Column({
    name: "left_reason",
    type: "enum",
    enum: DriverLeftReason,
    enumName: "driver_left_reason",
    nullable: true,
  })
  leftReason: DriverLeftReason | null;

  @Column({ name: "left_at", type: "timestamptz", nullable: true })
  leftAt: Date | null;

  @Column({ name: "left_by_id", type: "uuid", nullable: true })
  leftById: string | null;

  @ManyToOne(() => User, { nullable: true, onDelete: "SET NULL" })
  @JoinColumn({ name: "left_by_id" })
  leftBy?: User | null;

  /**
   * When an admin sent the driver to collections (D81); null = not in collections. A flag on an inactive driver, like
   * `archivedAt`, so removing them from collections restores exactly what they were.
   */
  @Column({
    name: "sent_to_collections_at",
    type: "timestamptz",
    nullable: true,
  })
  sentToCollectionsAt: Date | null;

  @Column({ name: "sent_to_collections_by_id", type: "uuid", nullable: true })
  sentToCollectionsById: string | null;

  @ManyToOne(() => User, { nullable: true, onDelete: "SET NULL" })
  @JoinColumn({ name: "sent_to_collections_by_id" })
  sentToCollectionsBy?: User | null;

  /**
   * The driver's login (a `users` row with role `driver`), created on approval. Null for
   * drivers approved before driver logins existed.
   */
  @Column({ name: "user_id", type: "uuid", nullable: true })
  userId: string | null;

  /** Foreign key to `users`. `OneToOne` also makes `user_id` unique: one login per driver. */
  @OneToOne(() => User, { nullable: true })
  @JoinColumn({ name: "user_id" })
  user?: User | null;

  /**
   * The driver's id in the old system, for drivers imported from it (D44); null for drivers created here.
   * Unique, so re-running the import updates the same driver instead of creating a duplicate. Postgres allows
   * any number of NULLs under a unique constraint, so drivers created here are not affected.
   */
  @Column({ name: "legacy_id", type: "uuid", nullable: true, unique: true })
  legacyId: string | null;

  @CreateDateColumn({ name: "created_at", type: "timestamptz" })
  createdAt: Date;

  @UpdateDateColumn({ name: "updated_at", type: "timestamptz" })
  updatedAt: Date;
}
